import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import en from "../assets/client/locales/en.mjs";
import zhCN from "../assets/client/locales/zh-CN.mjs";
import zhHant from "../assets/client/locales/zh-Hant.mjs";
import { isRuntimeLocaleKey } from "./runtime-locale-policy.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = path.join(root, "extension", "core", "runtime-locales");
const locales = Object.freeze({ en, "zh-CN": zhCN, "zh-Hant": zhHant });
const checkOnly = process.argv.includes("--check");
const keys = Object.keys(en).filter(isRuntimeLocaleKey);
const generatedHeader = "// Generated by scripts/generate-runtime-locales.mjs. Do not edit directly.\n";

await writeCatalog("keys.mjs", `${generatedHeader}export default Object.freeze(${JSON.stringify(keys)});\n`);

for (const [locale, messages] of Object.entries(locales)) {
  const values = keys.map(key => {
    if (typeof messages[key] !== "string") throw new Error(`Missing ${locale} runtime message: ${key}`);
    return messages[key];
  });
  const source = `${generatedHeader}import { createRuntimeCatalog } from "../runtime-catalog.mjs";\nexport default createRuntimeCatalog(${JSON.stringify(values)});\n`;
  await writeCatalog(`${locale}.mjs`, source);
}

async function writeCatalog(name, source) {
  const output = path.join(outputDirectory, name);
  if (checkOnly) {
    const current = await fs.readFile(output, "utf8").catch(() => "");
    if (current !== source) throw new Error(`${path.relative(root, output)} is stale. Run node scripts/generate-runtime-locales.mjs.`);
  } else {
    await fs.mkdir(outputDirectory, { recursive: true });
    await fs.writeFile(output, source, "utf8");
  }
}

console.log(`${checkOnly ? "Verified" : "Generated"} ${Object.keys(locales).length} runtime locale catalogs.`);
