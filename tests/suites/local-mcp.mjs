import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import http from "node:http";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { setTimeout as delay } from "node:timers/promises";
import { savePairing } from "../../integrations/local-mcp/pairing.mjs";
import { localConnection, callBridge } from "../../integrations/local-mcp/launcher.mjs";
import { openBoardStore } from "../../integrations/local-mcp/board-store.mjs";
import { startBridge } from "../../integrations/local-mcp/http-bridge.mjs";
import { createMcpHandler } from "../../integrations/local-mcp/mcp.mjs";
import { applyBotPatch } from "../../integrations/local-mcp/patch.mjs";
import { briefContext } from "../../extension/core/bot-task-context.mjs";

const directory = await fs.mkdtemp(path.join(os.tmpdir(), "ampira-local-mcp-test-"));
const now = new Date().toISOString();
const action = (id, type, data = {}) => ({ schemaVersion: 1, id, type, createdAt: now, ...data });
let store, bridge, child, daemonConnection;
try {
  store = await openBoardStore(directory);
  const boardId = store.boardId;
  await assert.rejects(openBoardStore(directory), { code: "data-directory-in-use" });
  bridge = await startBridge(store, 0);
  const headers = { Authorization: `Bearer ${store.token}`, "Content-Type": "application/json" };
  const request = (route, options = {}) => fetch(bridge.endpoint + route, { headers, ...options });
  const code = "f".repeat(64), extensionId = "a".repeat(32);
  await savePairing(directory, { code, extensionId, expiresAt: Date.now() + 60000 });
  const pair = value => request("/pair", { method: "POST", headers: { "Content-Type": "application/json", "X-Ampira-Extension": extensionId }, body: JSON.stringify({ code: value }) });
  assert.equal((await pair("0".repeat(64))).status, 401);
  assert.equal((await pair(code)).status, 200);
  assert.equal((await pair(code)).status, 200, "a lost pairing response can be retried before acknowledgement");
  assert.equal((await request("/pair", { method: "POST", headers: { "Content-Type": "application/json", "X-Ampira-Extension": extensionId, Origin: `chrome-extension://${"b".repeat(32)}` }, body: JSON.stringify({ code }) })).status, 403);
  await request("/pair/finish", { method: "POST", body: JSON.stringify({ code }) });
  assert.equal((await pair(code)).status, 401, "acknowledged setup codes cannot be reused");
  await assert.rejects(savePairing(directory, { code, extensionId, expiresAt: Date.now() - 1 }));
  assert.equal((await fetch(bridge.endpoint + "/health")).status, 401);
  assert.equal((await request("/health", { headers: { ...headers, Origin: "https://example.com" } })).status, 403);
  assert.equal((await request("/health", { headers: { ...headers, Origin: "null" } })).status, 403);
  const rebound = await new Promise((resolve, reject) => {
    const call = http.get(bridge.endpoint + "/health", { headers: { ...headers, Host: "attacker.example" } }, response => { response.resume(); resolve(response.statusCode); });
    call.on("error", reject);
  });
  assert.equal(rebound, 403);
  assert.equal((await request("/health", { headers: { ...headers, Origin: `chrome-extension://${"a".repeat(32)}` } })).status, 200);
  assert.equal((await request("/v1/../../connection.json")).status, 404);
  assert.equal((await request("/v1/inbox/one.json", { method: "PUT", body: JSON.stringify(action("two", "message", { text: "Mismatch" })) })).status, 409);
  const send = async (value) => {
    const response = await request(`/v1/inbox/${value.id}.json`, { method: "PUT", body: JSON.stringify(value) });
    assert.equal(response.status, 200); return response.json();
  };
  const summaryRequest = { requests: [{ id: 'http-summary', locale: 'zh-CN', title: 'A product update', excerpt: 'The display improves for existing devices.' }], resultIds: ['http-summary'] };
  assert.equal((await request('/v1/summaries.json', { method: 'POST', body: JSON.stringify(summaryRequest) })).status, 200);
  const summaryTask = store.getPending();
  assert.equal(summaryTask.kind, 'summary');
  const summaryMcp = createMcpHandler(store);
  await summaryMcp({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'summary-test', version: '1' } } });
  const summaryDone = await summaryMcp({ jsonrpc: '2.0', id: 2, method: 'tools/call', params: { name: 'ampira_complete_task', arguments: { taskId: summaryTask.id, summaries: [{ id: 'http-summary', title: '产品显示功能更新', summary: ['这次更新改善显示效果，并支持现有设备。'] }] } } });
  assert.equal(summaryDone.result.isError, false);
  assert.equal(store.getPending(), null);
  const translatedResponse = await request('/v1/summaries.json', { method: 'POST', body: JSON.stringify(summaryRequest) });
  const translatedResult = await translatedResponse.json();
  assert.equal(translatedResult.results[0].status, 'completed');
  assert.equal(translatedResult.results[0].result.title, '产品显示功能更新');
  for (const kind of ["weather", "todos", "news"]) assert.equal((await request(`/v1/${kind}.json`)).status, 404);
  assert.equal((await request("/v1/inbox/todo.json", { method: "PUT", body: JSON.stringify(action("todo", "todo.create", { text: "Stay in Ampira" })) })).status, 400);
  const firstQuestion = action("question-1", "message", { text: "Synthetic question one" });
  await send(firstQuestion);
  assert.equal((await send(firstQuestion)).duplicate, true);
  assert.equal((await request("/v1/inbox/question-1.json", { method: "PUT", body: JSON.stringify({ ...firstQuestion, text: "Changed" }) })).status, 409);
  await send(action("question-2", "message", { text: "Synthetic question two" }));
  const firstBatch = store.getPending();
  assert.deepEqual(firstBatch.messages.map((item) => item.id), ["question-1"], "new arrivals wait for the active batch");
  const mcp = createMcpHandler(store);
  const rpc = (method, params) => mcp({ jsonrpc: "2.0", id: 1, method, params });
  assert.equal((await rpc("tools/list")).error.code, -32000);
  const initialized = await rpc("initialize", { protocolVersion: "2025-11-25", capabilities: {}, clientInfo: { name: "synthetic", version: "1" } });
  assert.equal(initialized.result.protocolVersion, "2025-11-25");
  assert.deepEqual((await rpc("tools/list")).result.tools.map((tool) => tool.name), ["ampira_get_pending", "ampira_complete_task", "ampira_get_module", "ampira_publish"]);
  const call = async (name, args = {}) => (await rpc("tools/call", { name, arguments: args })).result;
  const replyPatch = { id: "answer-1", module: "replies", upsert: { items: [{ id: "reply-1", replyTo: "question-1", text: "Synthetic answer", createdAt: now }] } };
  assert.equal((await call("ampira_publish", replyPatch)).isError, false);
  assert.equal(store.getPending().messages[0].id, "question-2");
  assert.equal(JSON.parse((await call("ampira_publish", replyPatch)).content[0].text).duplicate, true);
  assert.equal((await call("ampira_publish", { ...replyPatch, module: "news" })).isError, true);
  assert.equal((await call("ampira_publish", { id: "unlinked", module: "replies", upsert: { items: [{ id: "r", replyTo: "missing", text: "Not accepted", createdAt: now }] } })).isError, true);
  await send(action("question-3", "message", { text: "Synthetic question three" }));
  await call("ampira_publish", { id: "answer-2", module: "replies", upsert: { items: [{ id: "reply-2", replyTo: "question-2", text: "Second", createdAt: now }] } });
  assert.equal(store.getPending().messages[0].id, "question-3");
  assert.equal((await call("ampira_publish", { id: "brief-1", module: "today", set: { brief: "Synthetic brief" } })).isError, false);
  const unchangedAt = store.module("today").updatedAt;
  await call("ampira_publish", { id: "brief-2", module: "today", set: { brief: "Synthetic brief" } });
  assert.equal(store.module("today").updatedAt, unchangedAt, "no-op publication preserves timestamps");
  await call("ampira_publish", { id: "answer-edit", module: "replies", upsert: { items: [{ id: "reply-1", text: "Updated answer" }] } });
  assert.equal(store.module("replies").data.items.find(item => item.id === "reply-1").replyTo, "question-1", "partial replies preserve unchanged fields");
  const replyResponse = await request("/v1/replies.json"), etag = replyResponse.headers.get("etag");
  assert.equal((await request("/v1/replies.json", { headers: { ...headers, "If-None-Match": etag } })).status, 304);
  assert((JSON.stringify(await call("ampira_get_pending"))).includes("question-3"));
  assert(!JSON.stringify(await rpc("tools/list")).includes(store.token), "MCP responses never contain the pairing credential");
  await assert.rejects(store.publish(JSON.parse('{"id":"bad","module":"today","set":{"__proto__":{"polluted":true}}}')));

  await bridge.close(); bridge = null;
  await store.close(); store = null;
  const departed = spawn(process.execPath, ["-e", ""], { stdio: "ignore", windowsHide: true });
  await once(departed, "exit");
  await fs.writeFile(path.join(directory, "server.lock"), String(departed.pid));
  store = await openBoardStore(directory);
  assert.equal(store.boardId, boardId);
  assert.equal((await store.syncSummaries(summaryRequest)).results[0].status, "completed", "verified summaries survive a service restart without a new task");
  assert.equal(store.module("today").data.brief, "Synthetic brief");
  assert.equal((await store.submit(firstQuestion)).duplicate, true, "restart preserves action receipts");
  assert.equal((await store.publish(replyPatch)).duplicate, true, "restart preserves publication receipts");
  await store.close(); store = null;

  // Exercise the actual executable with newline-delimited MCP and a real loopback listener.
  const probe = http.createServer(); probe.listen(0, "127.0.0.1"); await once(probe, "listening");
  const port = probe.address().port; await new Promise(resolve => probe.close(resolve));
  child = spawn(process.execPath, [path.resolve("integrations/local-mcp/client.mjs"), "--data-dir", directory, "--port", String(port)], { stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
  let stderr = "", stdout = "";
  child.stderr.setEncoding("utf8"); child.stderr.on("data", (chunk) => { stderr += chunk; });
  child.stdout.setEncoding("utf8");
  const responses = new Map();
  child.stdout.on("data", chunk => {
    stdout += chunk;
    let end;
    while ((end = stdout.indexOf("\n")) >= 0) {
      const message = JSON.parse(stdout.slice(0, end)); stdout = stdout.slice(end + 1);
      responses.get(message.id)?.(message);
    }
  });
  const sendRpc = (id, method, params) => new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("MCP response timeout")), 10000);
    responses.set(id, (value) => { clearTimeout(timer); responses.delete(id); resolve(value); });
    child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id, method, params }) + "\n");
  });
  assert.equal((await sendRpc(1, "initialize", { protocolVersion: "2025-11-25", capabilities: {}, clientInfo: { name: "synthetic-client", version: "1" } })).result.serverInfo.name, "ampira-local-mcp");
  daemonConnection = await localConnection(directory);
  child.stdin.write('{"jsonrpc":"2.0","method":"notifications/initialized"}\n');
  assert.equal((await sendRpc(2, "tools/list")).result.tools.length, 4);
  const { token } = JSON.parse(await fs.readFile(path.join(directory, "connection.json"), "utf8"));
  assert.equal((await fetch(`http://127.0.0.1:${port}/health`, { headers: { Authorization: `Bearer ${token}` } })).status, 200);
  const currentTask = JSON.parse((await sendRpc(3, "tools/call", { name: "ampira_get_pending", arguments: {} })).result.content[0].text).pending;
  assert(currentTask.messages.some(item => item.id === "question-3"));
  const answered = await sendRpc(4, "tools/call", { name: "ampira_complete_task", arguments: { taskId: currentTask.id, replies: [{ id: "question-3", text: "程序已补齐回复编号与时间。" }] } });
  assert.equal(answered.result.isError, false);
  const briefMaterial = briefContext([{ title: "产品显示更新", excerpt: "这次更新改善显示效果，并支持现有设备。", source: "Synthetic", url: "https://example.com/evidence", publishedAt: now }]);
  const briefPayload = { owner: "browser-fixture", request: { id: "brief-fixture", date: now.slice(0, 10), locale: "zh-CN", fingerprint: "brief-content-fixture", ...briefMaterial } };
  const queued = await fetch(`http://127.0.0.1:${port}/v1/briefs.json`, { method: "POST", headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" }, body: JSON.stringify(briefPayload) });
  assert.equal(queued.status, 200);
  const pendingBrief = JSON.parse((await sendRpc(5, "tools/call", { name: "ampira_get_pending", arguments: {} })).result.content[0].text).pending;
  assert.equal(pendingBrief.kind, "brief");
  const completedBrief = await sendRpc(6, "tools/call", { name: "ampira_complete_task", arguments: { taskId: pendingBrief.id, brief: "产品更新改善显示效果，现有设备可以获得支持。", sourceIds: [briefMaterial.context[0].id] } });
  assert.equal(completedBrief.result.isError, false);
  const todayResponse = await fetch(`http://127.0.0.1:${port}/v1/today.json`, { headers: { Authorization: `Bearer ${token}` } });
  const today = await todayResponse.json();
  assert.equal(today.data.nativeBrief.taskId, "brief-fixture");
  assert.equal(today.data.nativeBrief.sources[0].url, "https://example.com/evidence");
  const exit = once(child, "exit"); child.stdin.end();
  assert.equal((await exit)[0], 0); child = null;
  assert(!stderr.includes(token));
  assert.equal((await callBridge(daemonConnection, "/health")).app, "ampira-local-mcp");
  await callBridge(daemonConnection, "/shutdown", {});
  for (let count = 0; count < 30 && await fs.access(path.join(directory, "server.lock")).then(() => true, () => false); count++) await delay(100);
  await assert.rejects(fs.access(path.join(directory, "server.lock")), { code: "ENOENT" });
  daemonConnection = null;

  const runCommand = args => new Promise((resolve, reject) => {
    const process = spawn(globalThis.process.execPath, args, { windowsHide: true });
    let output = "", errors = "";
    process.stdout.on("data", chunk => { output += chunk; }); process.stderr.on("data", chunk => { errors += chunk; });
    process.on("error", reject); process.on("close", code => code === 0 ? resolve(output) : reject(new Error(`Local setup command failed: ${errors}`)));
  });
  const setupOutput = await runCommand([path.resolve("integrations/local-mcp/connect.mjs"), "--data-dir", directory, "--port", String(port), "--code", code, "--extension", extensionId, "--expires", String(Date.now() + 60000)]);
  daemonConnection = await localConnection(directory);
  const setupResult = JSON.parse(setupOutput);
  assert.equal(setupResult.status, "local-service-ready");
  assert(!setupOutput.includes(daemonConnection.token), "setup command prints only public client configuration");
  const paired = await fetch(daemonConnection.endpoint + "/pair", { method: "POST", headers: { "Content-Type": "application/json", "X-Ampira-Extension": extensionId }, body: JSON.stringify({ code }) });
  assert.equal(paired.status, 200);
  child = spawn(setupResult.mcpServer.command, setupResult.mcpServer.args, { stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
  let clientOutput = "";
  child.stdout.on("data", chunk => { clientOutput += chunk; }); child.stderr.resume();
  const clientExit = once(child, "exit");
  child.stdin.end(JSON.stringify({ jsonrpc: "2.0", id: 41, method: "initialize", params: { protocolVersion: "2025-11-25", capabilities: {}, clientInfo: { name: "setup-test", version: "1" } } }) + "\n" + JSON.stringify({ jsonrpc: "2.0", id: 42, method: "tools/list" }) + "\n");
  assert.equal((await clientExit)[0], 0); child = null;
  assert.equal(JSON.parse(clientOutput.trim().split("\n")[1]).result.tools.length, 4);
  assert.equal((await callBridge(daemonConnection, "/health")).app, "ampira-local-mcp", "the reusable service remains available after a client exits");
  await runCommand([path.resolve("integrations/local-mcp/connect.mjs"), "--data-dir", directory, "--stop"]);
  for (let count = 0; count < 30 && await fs.access(path.join(directory, "server.lock")).then(() => true, () => false); count++) await delay(100);
  await assert.rejects(fs.access(path.join(directory, "server.lock")), { code: "ENOENT" });
  daemonConnection = null;
} finally {
  daemonConnection ||= await localConnection(directory).catch(() => null);
  if (daemonConnection) { await callBridge(daemonConnection, "/shutdown", {}).catch(() => {}); await delay(300); }
  if (child) { const exited = once(child, "exit"); child.kill(); await exited; }
  await bridge?.close(); await store?.close();
  const resolved = path.resolve(directory);
  assert(resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith("ampira-local-mcp-test-"));
  await fs.rm(resolved, { recursive: true, force: true });
}
assert.throws(() => applyBotPatch(null, { schemaVersion: 1, id: "p", module: "today", createdAt: now, bot: "Test", upsert: { events: [] } }, now));
console.log("local MCP integration tests passed");
